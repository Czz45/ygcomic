    private val s2t = HashMap<Char, Char>()
    private val t2s = HashMap<Char, Char>()

    init {
        PAIRS.split(',').forEach { part ->
            val idx = part.indexOf('=')
            if (idx == 1 && part.length == 3) {
                val s = part[0]
                val t = part[2]
                s2t[s] = t
                t2s[t] = s
            }
        }
    }

    fun toTraditional(text: String): String {
        if (s2t.isEmpty()) return text
        val out = StringBuilder(text.length)
        text.forEach { out.append(s2t[it] ?: it) }
        return out.toString()
    }

    fun toSimplified(text: String): String {
        if (t2s.isEmpty()) return text
        val out = StringBuilder(text.length)
        text.forEach { out.append(t2s[it] ?: it) }
        return out.toString()
    }
